static unsigned adlibFieldDistance(unsigned a, unsigned b) {
	return a > b ? a - b : b - a;
}
static byte adlibToGmProgram(const byte *patch) {
	unsigned bestScore = ~0u;
	byte best = 0;
	for (unsigned program = 0; program < 128; ++program) {
		const byte *ref = adlibGmReference[program];
		unsigned score = 0;
		for (unsigned op = 0; op < 2; ++op) {
			const unsigned k = op * 5;
			// Operator frequency multiple and sustained/percussive envelope.
			score += 8 * adlibFieldDistance(patch[k] & 15, ref[k] & 15);
			score += (patch[k] ^ ref[k]) & 0x20 ? 32 : 0;
			score += (patch[k] & 0xC0) == (ref[k] & 0xC0) ? 0 : 4;
			// Waveform occupies only the low two bits of the iMUSE byte.
			score += (patch[k+4] & 3) == (ref[k+4] & 3) ? 0 : 24;
			for (unsigned e = 2; e <= 3; ++e) {
				score += adlibFieldDistance(patch[k+e] >> 4, ref[k+e] >> 4);
				score += adlibFieldDistance(patch[k+e] & 15, ref[k+e] & 15);
			}
		}
		// Modulator level affects FM depth; carrier level is volume only.
		score += adlibFieldDistance(patch[1] & 63, ref[1] & 63) / 2;
		score += ((patch[10] ^ ref[10]) & 1) ? 48 : 0;
		score += 4 * adlibFieldDistance((patch[10] >> 1) & 7, (ref[10] >> 1) & 7);
		if (score < bestScore) { bestScore = score; best = program; }
	}
	return best;
}
